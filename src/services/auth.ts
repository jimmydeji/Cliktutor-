import { auth, db } from '../firebase';
import { 
  createUserWithEmailAndPassword, 
  signInWithEmailAndPassword, 
  signOut,
  onAuthStateChanged,
  User
} from 'firebase/auth';
import { doc, setDoc } from 'firebase/firestore';
import { StudentProfile, PaymentRequest } from '../types';
import { savePaymentRequest } from './storage';

export const signUp = async (email: string, password: string, profile: Omit<StudentProfile, 'id'>) => {
  const userCredential = await createUserWithEmailAndPassword(auth, email, password);
  const user = userCredential.user;
  
  const sanitizedProfile = Object.fromEntries(
    Object.entries({
      ...profile,
      id: user.uid,
      registeredAt: new Date().toISOString()
    }).filter(([_, v]) => v !== undefined)
  );

  await setDoc(doc(db, 'studentProfile', user.uid), sanitizedProfile);

  // Automatically create a pending payment request
  await savePaymentRequest({
    id: '', // Will be generated by Firestore
    userId: user.uid,
    studentName: profile.name,
    phoneNumber: profile.phoneNumber,
    tier: 'Trial/Pending',
    amount: 0,
    status: 'pending',
    createdAt: new Date().toISOString()
  });
  
  return user;
};

export const signIn = async (email: string, password: string) => {
  return await signInWithEmailAndPassword(auth, email, password);
};

export const logOut = async () => {
  await signOut(auth);
};

export const subscribeToAuthChanges = (callback: (user: User | null) => void) => {
  return onAuthStateChanged(auth, callback);
};
